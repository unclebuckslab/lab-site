// Turns design/fog.tokens.json (DTCG) into src/styles/tokens.css: light by default, dark under
// prefers-color-scheme. Small on purpose; swap for Terrazzo when the tokens move to lab-hq/design.
// Also checks contrast: the build fails if any required pair drops below WCAG 2.2 AA.
import { readFile, writeFile } from 'node:fs/promises';

const tokens = JSON.parse(await readFile(new URL('../design/fog.tokens.json', import.meta.url), 'utf8'));

const dim = (v) => `${v.value}${v.unit}`;
const fam = (list) => list.map((f) => (/\s/.test(f) ? `'${f}'` : f)).join(', ');

const lines = [];
for (const [k, t] of Object.entries(tokens.font)) if (!k.startsWith('$')) lines.push(`  --font-${k}: ${fam(t.$value)};`);
for (const [k, t] of Object.entries(tokens.size)) if (!k.startsWith('$')) lines.push(`  --size-${k}: ${dim(t.$value)};`);

const colors = (mode) =>
  Object.entries(tokens.color[mode])
    .filter(([k]) => !k.startsWith('$'))
    .map(([k, t]) => [k, t.$value.hex]);

const light = colors('light');
const dark = colors('dark');

// Contrast check (relative luminance, WCAG 2.x).
const lum = (hex) => {
  const c = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4));
  return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
};
const ratio = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};
const failures = [];
for (const [mode, list] of [['light', light], ['dark', dark]]) {
  const c = Object.fromEntries(list);
  const need = [
    ['text', 'ground', 4.5], ['text', 'surface', 4.5], ['text', 'tint', 4.5],
    ['text-secondary', 'ground', 4.5], ['text-secondary', 'surface', 4.5], ['text-secondary', 'tint', 4.5],
    ['accent', 'ground', 4.5], ['on-accent', 'accent', 4.5], ['on-lead', 'lead', 4.5],
    ['rule', 'ground', 3], ['rule-strong', 'ground', 3],
  ];
  for (const k of Object.keys(c).filter((k) => k.startsWith('kind-'))) {
    need.push(['on-kind', k, 4.5], [k, 'ground', 3]);
  }
  for (const [fg, bg, min] of need) {
    const r = ratio(c[fg], c[bg]);
    if (r < min) failures.push(`${mode}: ${fg} on ${bg} is ${r.toFixed(2)}:1, needs ${min}:1`);
  }
}
if (failures.length) {
  console.error('tokens: contrast check failed\n  ' + failures.join('\n  '));
  process.exit(1);
}

const css = `/* Generated by scripts/build-tokens.mjs from design/fog.tokens.json. Don't edit by hand. */
:root {
  color-scheme: light dark;
${lines.join('\n')}
${light.map(([k, v]) => `  --color-${k}: ${v};`).join('\n')}
}

@media (prefers-color-scheme: dark) {
  :root {
${dark.map(([k, v]) => `    --color-${k}: ${v};`).join('\n')}
  }
}
`;
await writeFile(new URL('../src/styles/tokens.css', import.meta.url), css);
console.log(`tokens: wrote ${light.length} colors per mode; contrast check passed`);
